// Carved thiscall getter pairs, converted as one family.
//
// Each pair is two of the three shapes the carve lane repeats:
// mov eax,[ecx]; ret and mov eax,[ecx+4]; ret, at 0x10 intervals,
// each with a rel32 call/jmp target proving its start and a decoded
// ret proving its end. No caller names any of them, so each keeps an
// address-derived class name rather than claiming a retail identity
// the image does not support. The class is a layout view of two
// adjacent accessors over an 8-byte prefix, not a real type.
//
// One half of a pair is absent where another queue already landed that
// address; this unit holds only what the ledger still claims here.

